// Language management
function getLang() {
  return localStorage.getItem("blues-jam-lang") || "es";
}

function setLang(lang) {
  localStorage.setItem("blues-jam-lang", lang);
  applyTranslations();
}

function t(key) {
  const lang = getLang();
  return (translations[lang] && translations[lang][key]) || translations.en[key] || key;
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      el.placeholder = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  // Update lang selector highlight
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active-lang", btn.dataset.lang === getLang());
  });
}

// Render language switcher
function renderLangSwitcher(containerId) {
  const container = document.getElementById(containerId);
  if (!container) return;
  const langs = [
    { code: "en", label: "EN" },
    { code: "es", label: "ES" },
    { code: "ru", label: "RU" },
    { code: "pl", label: "PL" },
    { code: "zh", label: "中文" },
    { code: "ja", label: "日本語" }
  ];
  container.innerHTML = langs.map(l =>
    `<button class="lang-btn small secondary" data-lang="${l.code}" onclick="setLang('${l.code}')">${l.label}</button>`
  ).join(" ");
}

// Auto-apply on load
document.addEventListener("DOMContentLoaded", () => {
  renderLangSwitcher("lang-switcher");
  applyTranslations();
});
